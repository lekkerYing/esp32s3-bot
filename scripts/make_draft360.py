"""Guess table for the 360M board build, made from what the 4-bit model ITSELF answers.

For every training/validation question the 4-bit smolFem answers greedily (output limited to the allowed words, like the board).
Records = [question + the model's own answer] first, then [question + the training answer] as a fallback. The board looks up the
last few tokens it has seen, and guesses the next 23 from the first record that matches best; the model then checks all of them in
one pass, so the answer is exactly what the model says, only faster.

usage: python make_draft360.py [model folder]      writes sd-stream/smol_360/draft_data.h
"""
import json, os, re, sys, time
import torch
from transformers import AutoTokenizer, AutoModelForCausalLM, LogitsProcessor, LogitsProcessorList

MODEL = sys.argv[1] if len(sys.argv) > 1 else "smolFem360-qat-int4g64"
DATA = os.environ.get("DATA_DIR", "dataset")   # folder with the cleaned train and valid files
OUTH = os.environ.get("DRAFT_OUT", "../sketch/smol_360/draft_data.h")
MAXNEW = 80                                   # the board's K/V cache holds 96 positions: prompt + answer
tok = AutoTokenizer.from_pretrained(MODEL); tok.padding_side = "left"
if tok.pad_token_id is None:
    tok.pad_token = tok.eos_token
rows = []
for fn in ("train_clean_text.jsonl", "valid_clean_text.jsonl"):
    for l in open(os.path.join(DATA, fn), encoding="utf-8"):
        if l.strip():
            mm = re.match(r"^Instruction:\s*(.*?)\nResponse:\s*(.*)$", json.loads(l)["text"], re.S)
            rows.append((mm.group(1).strip(), mm.group(2).strip()))
seen = set(); uniq = []
for q, a in rows:
    if (q, a) not in seen:
        seen.add((q, a)); uniq.append((q, a))
allowed = {tok.eos_token_id}
for q, a in uniq:
    allowed.update(tok(" " + a, add_special_tokens=False)["input_ids"]); allowed.update(tok(a, add_special_tokens=False)["input_ids"])
mask = torch.full((len(tok),), float("-inf")); mask[sorted(allowed)] = 0.0; mask = mask.cuda()


class Allowed(LogitsProcessor):
    def __call__(self, input_ids, scores):
        return scores + mask


m = AutoModelForCausalLM.from_pretrained(MODEL, dtype=torch.float32).cuda().eval()
questions = sorted({q for q, a in uniq})
own = {}
t0 = time.time(); BS = 12
for i in range(0, len(questions), BS):
    qs = questions[i:i + BS]
    enc = tok([f"Instruction: {q}\nResponse:" for q in qs], return_tensors="pt", padding=True, add_special_tokens=False).to("cuda")
    with torch.no_grad():
        out = m.generate(**enc, do_sample=False, max_new_tokens=MAXNEW, logits_processor=LogitsProcessorList([Allowed()]),
                         pad_token_id=tok.pad_token_id, eos_token_id=tok.eos_token_id)
    for q, row in zip(qs, out[:, enc["input_ids"].shape[1]:]):
        ids = row.tolist()
        if tok.eos_token_id in ids:
            ids = ids[:ids.index(tok.eos_token_id) + 1]
        own[q] = ids
    print(f"{i + len(qs)}/{len(questions)} questions, {time.time() - t0:.0f} s", flush=True)

table = []
nrec = 0
for q in questions:                                                   # the model's own answers first (they win ties)
    p = tok(f"Instruction: {q}\nResponse:", add_special_tokens=False)["input_ids"]
    table += p + own[q] + [0xFFFF]; nrec += 1
for q, a in uniq:                                                     # then the training answers
    prompt = f"Instruction: {q}\nResponse:"
    full = (tok(prompt + " " + a, add_special_tokens=False)["input_ids"] + [tok.eos_token_id])[:512]
    table += full + [0xFFFF]; nrec += 1
assert max(t for t in table if t != 0xFFFF) < 0xFFFF
same = sum(1 for q, a in uniq if tok.decode(own[q]).strip() == a.strip())
print(f"the model's answer equals the training answer for {same} of {len(uniq)} records")
out = ["// Generated by scripts/make_draft360.py: the 4-bit model's own answers to the training questions, then the training answers (0xFFFF separates records).",
       "// Used for speculative decoding: guesses of the next tokens that the model then checks in one pass.",
       f"#define DRAFT_N {len(table)}", "static const uint16_t draft_tab[DRAFT_N] = {"]
for i in range(0, len(table), 16):
    out.append(",".join(str(x) for x in table[i:i + 16]) + ",")
out.append("};")
open(OUTH, "w").write("\n".join(out) + "\n")
print(f"{nrec} records, {len(table)} tokens -> {OUTH}")
